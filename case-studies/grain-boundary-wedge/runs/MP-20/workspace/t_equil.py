"""
Equilibrium (t -> infinity) state.

At equilibrium the flux vanishes everywhere, so mu = -sigma_gb Omega is
uniform, and with the surface condition sigma_gb(0)=0 the ONLY admissible
uniform value is zero:

    sigma_gb(z, inf) = 0   for all z  in [0,h] .

The wedge that produces this is the solution of the elasticity relation

    (2/pi) int_0^h S(z,zeta) u_inf'(zeta) dzeta = 1        (sigma0 normalised to 1)

i.e. in dimensionless form  A1 w_inf = 1  with  w_inf = E*-scaled opening.

This is a *first-kind integral equation* for w' and is well conditioned (no
second derivative).  We solve it by collocation:

    A1 w = 1  ->  w = A1^{-1} 1
(w is determined up to constants; we fix w(0)=0, i.e. the opening is measured
relative to the surface, which is what the wedge shape means).

Then the stress intensity factor at the blocked interface z=h is read off from
the behaviour of sigma_gb just below h.  Because the interface forbids sliding
and diffusion, the wedge tip there is *sharp*: sigma_gb stays zero at the tip
but the opening derivative w' has a square-root-type singularity, giving
sigma ~ K/sqrt(2 pi (h-z)).  We measure K from the elastic field generated by
the equilibrium wedge.
"""

import numpy as np
from numpy.polynomial.legendre import leggauss
import gb3

xq, wq = leggauss(1500); xq = 0.5 * (xq + 1); wq = 0.5 * wq

n = 40
sn = np.linspace(0.0, 1.0, n + 1)
# Use interior Gauss-Legendre nodes for the collocation (avoid the singular
# endpoint s=0 row).
sg, wg = leggauss(n)
s_int = 0.5 * (sg + 1.0)
E = gb3.elasticity_matrix(s_int, xq, wq)      # n x n
# E has a null direction (constants: w=const -> w_x=0 -> A1 w=0).  Fix the
# gauge by pinning the average of w to zero: append the constraint.
#   [ E ]       [ 1 ]
#   [ 1 ] w =   [ 0 ]
# (n+1) x n least squares -> normal equations.
Aug = np.vstack([E, np.ones(n)[None, :]])
rhs = np.concatenate([np.ones(n), [0.0]])
w_int, *_ = np.linalg.lstsq(Aug, rhs, rcond=None)
print('equilibrium opening (E*-scaled) w(s):')
for k in range(0, n, max(1, n // 10)):
    print('  s=%.4f  w=%+.6f' % (s_int[k], w_int[k]))
print('  s=%.4f  w=%+.6f' % (s_int[-1], w_int[-1]))